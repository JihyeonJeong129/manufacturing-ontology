def _situation(sid: str, block: int, title: str, label: str, terms: str, steps: list[str],
               with_definition: bool = True) -> SectionDef:
    spans = []
    if with_definition:
        spans.append(S(block, "- 정의:", "$", "definition"))
    spans += [
        S(block, "- 현장 모습:", "$", "symptoms"),
        S(block, "- 데이터 신호:", "$", "signals"),
        S(block, "- 원인 후보:", "$", "causes"),
        S(block, "- 점검 순서:", "$", "checks"),
        S(block, "- 참고:", "$", "refs"),
    ]
    anchors = tuple(S(block, text, name=f"step{i}") for i, text in enumerate(steps, start=1))
    return SectionDef(sid, DOCX, sid.split("-")[1], title, label, tuple(spans), terms, anchors)


